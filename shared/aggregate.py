"""shared/aggregate.py — collect every projects/*/results.json into results/RESULTS.md.

Run from the repo root:  python shared/aggregate.py
Each project writes a results.json shaped like:
  {"project": "...", "metric": "accuracy", "unit": "%",
   "rows": [{"model": "...", "value": 91.2, "notes": "..."}], "run_at": "..."}
"""
import glob
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def load():
    out = []
    for path in sorted(glob.glob(os.path.join(ROOT, "projects", "*", "results.json"))):
        try:
            with open(path) as f:
                out.append(json.load(f))
        except Exception as e:  # noqa: BLE001
            print(f"skip {path}: {e}")
    return out


def render(blocks):
    lines = ["# Master results", "",
             "_Auto-generated by `shared/aggregate.py`. Do not edit by hand._", ""]
    if not blocks:
        lines.append("No `results.json` files found yet — run a project first.")
        return "\n".join(lines) + "\n"
    for b in blocks:
        metric = b.get("metric", "value")
        unit = b.get("unit", "")
        head = f"## {b.get('project','(unnamed)')} — {metric}"
        if unit:
            head += f" ({unit})"
        lines.append(head)
        lines.append(f"_run: {b.get('run_at','?')}_")
        lines.append("")
        lines.append("| model | value | notes |")
        lines.append("|-------|------:|-------|")
        for r in b.get("rows", []):
            lines.append(f"| {r.get('model','')} | {r.get('value','')} | {r.get('notes','')} |")
        lines.append("")
    return "\n".join(lines) + "\n"


def main():
    md = render(load())
    out = os.path.join(ROOT, "results", "RESULTS.md")
    with open(out, "w") as f:
        f.write(md)
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
